/**
 * TOKENS.md, the token reference, rewritten on every build from the Figma
 * export and tokens.css, so it can't drift from them. DESIGN.md, edited
 * directly, says which token to use for what; this lists them all. It's a
 * guide to choosing a token, not a copy of tokens.css: colours are listed by
 * name and use only, so nobody copies a hex value; scales keep their values,
 * because there the number is how you choose. Uses are the Figma descriptions.
 */
import { writeFile } from 'node:fs/promises'

import { slug as slugOf } from './shared.mjs'

/** Headings for the first segment of a name; anything new falls back to the segment itself. */
const GROUPS = {
  bg: 'Backgrounds',
  border: 'Lines',
  overlay: 'Overlays',
  text: 'Text',
  accent: 'Accent',
  status: 'Status',
  series: 'Chart series',
  focus: 'Focus',
  window: 'Window',
  spacing: 'Spacing',
  radius: 'Radius',
  'font-size': 'Font sizes',
  'font-family': 'Font families',
  opacity: 'Opacity',
  shadow: 'Shadows',
  titlebar: 'Layout',
  rail: 'Layout',
  card: 'Cards',
  row: 'Cards',
  ease: 'Motion',
  duration: 'Motion',
  weight: 'Font weights',
}

/** Text style groups, the first segment of a style's name, in the order the table lists them. */
const TYPE_GROUPS = ['Heading', 'Body', 'Label', 'Caption', 'Badge', 'Number']

const cssName = (figmaName) => `--${figmaName.replace(/\//g, '-')}`
const code = (text) => `\`${text}\``
const heading = (prefix) => GROUPS[prefix] ?? prefix[0].toUpperCase() + prefix.slice(1)

/** `--name: value;` declarations of one rule in tokens.css, trailing comments dropped. */
function declarations(css, selector) {
  const start = css.indexOf(`${selector} {`)
  if (start === -1) return new Map()
  const body = css.slice(start, css.indexOf('\n}', start))
  return new Map(
    [...body.matchAll(/^\s*(--[\w-]+):\s*(.+?);(?:\s*\/\*.*\*\/)?$/gm)].map(([, name, value]) => [name, value]),
  )
}

/** A Markdown table: a header row, then one row per item. */
const table = (header, rows) => [
  `| ${header.join(' | ')} |`,
  `| ${header.map(() => '---').join(' | ')} |`,
  ...rows.map((cells) => `| ${cells.map((c) => String(c ?? '').replace(/\|/g, '\\|')).join(' | ')} |`),
]

function groupBy(items, key) {
  const groups = new Map()
  for (const item of items) {
    const k = key(item)
    if (!groups.has(k)) groups.set(k, [])
    groups.get(k).push(item)
  }
  return groups
}

export async function writeReference({ path, variables, textStyles, shadows, code: codeTokens, css }) {
  const dark = declarations(css, ':root')
  const light = declarations(css, ':root.theme-light')
  // A font stack reads as its first font.
  const short = (value) => value.split(',')[0].replace(/^'|'$/g, '')

  const cssVars = variables.filter((v) => v.code)
  const colours = cssVars.filter((v) => v.type === 'COLOR')
  const others = cssVars.filter((v) => v.type !== 'COLOR')
  const out = []

  // Plain numbers read as text; expressions stay as code.
  const show = (value) => (value.includes('(') ? code(value) : value)

  out.push(
    '# Rove tokens',
    '',
    "<!-- Generated by npm run build from the Figma export and tokens.css. Don't edit it: change Figma, export and build. -->",
    '',
    'Every token by name and use, from Figma. [DESIGN.md](DESIGN.md) says which to use for what. The values are in `tokens.css`; Dark and Light differ only in colour and shadow.',
    '',
    '## Colour',
    '',
  )
  // Colours by name and use only, so nobody copies a hex.
  for (const [prefix, vars] of groupBy(colours, (v) => v.name.split('/')[0])) {
    out.push(
      `### ${heading(prefix)}`,
      '',
      ...table(
        ['Token', 'Use'],
        vars.map((v) => [code(cssName(v.name)), v.description]),
      ),
      '',
    )
  }

  out.push('## Scales', '')
  // Prefixes that share a heading (titlebar/ and rail/ are Layout) share a table.
  for (const [title, vars] of groupBy(others, (v) => heading(v.name.split('/')[0]))) {
    const value = (v) => dark.get(cssName(v.name))
    const px = (v) => value(v)?.match(/^([\d.]+)px$/)?.[1]
    // Pixel scales read smallest to largest; Figma lists late additions last.
    if (vars.every(px)) vars.sort((a, b) => px(a) - px(b))
    const rows = vars.map((v) => [code(cssName(v.name)), show(short(value(v))), v.description])
    out.push(`### ${title}`, '', ...table(['Token', 'Value', 'Use'], rows), '')
  }

  out.push(
    '## Text styles',
    '',
    'Apply a style with its class from `text-styles.css`. Each class reads four variables, `--type-<style>-size`, `-weight`, `-line-height` and `-letter-spacing`; set all four if you use them directly, and `text-transform: uppercase` for an uppercase style, which has no variable.',
    '',
  )
  out.push('| Style | Class | Size, weight | Case, tracking | Use |', '| --- | --- | --- | --- | --- |')
  // By group, as a type scale reads, then largest first; Figma lists late additions last.
  const group = (s) => {
    const at = TYPE_GROUPS.indexOf(s.name.split('/')[0])
    return at === -1 ? TYPE_GROUPS.length : at
  }
  const sorted = [...textStyles].sort(
    (a, b) => group(a) - group(b) || b.fontSize - a.fontSize || b.fontWeight - a.fontWeight,
  )
  for (const s of sorted) {
    const slug = slugOf(s.name)
    const numeric = s.boundVariables?.fontFamily === 'font-family/numeric' ? ', Questrial' : ''
    // Figma's description ends in a "Code:" handoff note; it's kept only when
    // it says more than the Class column.
    const [use, handoff] = s.description.split(/\s*Code:\s*/)
    const inCode = handoff && handoff !== `.type-${slug}` ? ` In code: ${handoff}` : ''
    const tracking = dark.get(`--type-${slug}-letter-spacing`)
    const look = [s.textCase === 'UPPER' && 'uppercase', tracking !== '0' && `+${tracking}`].filter(Boolean).join(', ')
    out.push(
      `| ${s.name} | ${code(`.type-${slug}`)} | ${s.fontSize}px ${dark.get(`--type-${slug}-weight`)}${numeric} | ${look || '–'} | ${`${use}${inCode}`.replace(/\|/g, '\\|')} |`,
    )
  }

  out.push(
    '',
    '## Shadows',
    '',
    "From Figma's `Shadow/*` effect styles. Each layer's colour is a variable, so the theme sets it.",
    '',
  )
  const shadowName = (style) =>
    `--shadow-${style.name
      .replace(/^Shadow\//, '')
      .toLowerCase()
      .replace(/\s+/g, '-')}`
  // Figma's effect style descriptions are sentences; in a table they lose the full stop.
  out.push(
    ...table(
      ['Token', 'Use'],
      shadows.map((s) => [code(shadowName(s)), s.description.replace(/\.$/, '')]),
    ),
  )

  const codeNames = Object.keys(codeTokens.tokens)
  out.push('', '## Code-only tokens', '', "What Figma can't hold, from `src/code-tokens.json`.", '')
  // Long or per-theme values (calc(), a focus outline) are named only; tokens.css has them.
  const shown = (n) => dark.get(n).length <= 24 && (light.get(n) ?? dark.get(n)) === dark.get(n)
  const codeRows = codeNames.map((n) => [
    code(n),
    heading(n.slice(2).split('-')[0]),
    shown(n) ? show(dark.get(n)) : 'In `tokens.css`',
  ])
  out.push(...table(['Token', 'Group', 'Value'], codeRows))

  await writeFile(path, `${out.join('\n')}\n`)
  return { colours: colours.length, others: others.length, styles: textStyles.length, code: codeNames.length }
}
